"""x6 verifier: adversarial round-trip fixtures for the hand-written hub spokes.

The original x6_fidelity fixtures are all generated by make_panel (sorted, string
keys, float64, regular freq, 6x12). Here: inputs that occur in practice but are not
covered there. Equality is checked by a different code path: explicit comparisons of
index levels (incl. level values/dtypes/names), per-level freq, value bit patterns
(NaN vs null distinguished), dtypes, column order, plus assert_frame_equal.

Also checks the "trusted freq" per-slice pandas view and HubNaive on a panel whose
instances have DIFFERENT frequencies (hub stores one global freq from instance 0).

Run: PYTHONPATH=.:experiments/container_independence $EXP_PY -W ignore \
       experiments/container_independence/scripts/x6_proto_hub_verify0_fidelity.py
"""

