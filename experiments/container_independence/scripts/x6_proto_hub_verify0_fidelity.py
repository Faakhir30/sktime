def pd_equal(a, b):
    if type(a) is not type(b):
        return False, f"type {type(a).__name__} != {type(b).__name__}"
    try:
        if isinstance(a, pd.Series):
            pd.testing.assert_series_equal(a, b, check_exact=True, check_freq=True)
        else:
            pd.testing.assert_frame_equal(a, b, check_exact=True, check_freq=True)
    except AssertionError as e:
        return False, "assert: " + str(e).strip().splitlines()[0][:150]
    ia, ib = a.index, b.index
    if type(ia) is not type(ib):
        return False, f"index type {type(ia).__name__} != {type(ib).__name__}"
    if list(ia.names) != list(ib.names):
        return False, f"names {ia.names} != {ib.names}"
    for i in range(ia.nlevels):
        la, lb = ia.get_level_values(i), ib.get_level_values(i)
        if la.dtype != lb.dtype:
            return False, f"level {i} dtype {la.dtype} != {lb.dtype}"
        if not la.equals(lb):
            return False, f"level {i} values differ: {list(la[:3])} vs {list(lb[:3])}"
    if getattr(ia, "freq", None) != getattr(ib, "freq", None):
        return False, f"freq {ia.freq} != {ib.freq}"
    return True, ""


def pl_equal(a, b):
    import polars as pl

    if type(a) is not type(b):
        return False, "type"
    if isinstance(a, pl.LazyFrame):
        a, b = a.collect(), b.collect()
    if a.schema != b.schema:
        return False, f"schema {dict(a.schema)} != {dict(b.schema)}"
    for c in a.columns:
        sa, sb = a[c], b[c]
        if not sa.is_null().equals(sb.is_null()):
            return False, f"null mask differs in {c}"
        if sa.dtype.is_float():
            na, nb = sa.is_nan().fill_null(False), sb.is_nan().fill_null(False)
            if not na.equals(nb):
                return False, f"NaN mask differs in {c} ({na.sum()} vs {nb.sum()})"
    return (a.equals(b, null_equal=True), "values differ")


def pa_equal(a, b):
    import pyarrow as pa
    import pyarrow.compute as pc

    if not a.schema.equals(b.schema, check_metadata=True):
        return False, f"schema {a.schema.types} != {b.schema.types}"
    for c in a.column_names:
        ca, cb = a.column(c), b.column(c)
        if not pc.is_null(ca).equals(pc.is_null(cb)):
            return False, f"null mask differs {c}"
        if pa.types.is_floating(ca.type):
            if not pc.is_nan(ca).fill_null(False).equals(pc.is_nan(cb).fill_null(False)):
                return False, f"NaN mask differs {c}"
    return a.equals(b), "values differ"


def fixtures():
    import polars as pl
    import pyarrow as pa

    fx = {}
    base = make_panel(4, 10, n_cols=2, n_levels=1)
    # 1. NaN in an instance key level
    k = base.reset_index()
    k.loc[k.h0 == "s1", "h0"] = np.nan
    fx["pd_nan_in_key_level"] = k.set_index(["h0", "time"])
    # 2. integer instance keys
    k = base.reset_index()
    k["h0"] = k["h0"].str[1:].astype(int)
    fx["pd_int_keys"] = k.set_index(["h0", "time"])
    # 3. nullable Float64 with NA
    nf = base.astype("Float64")
    nf.iloc[2, 0] = pd.NA
    fx["pd_nullable_Float64_NA"] = nf
    # 4. nullable Int64 with NA
    ni = (base * 100).round().astype("Int64")
    ni.iloc[2, 0] = pd.NA
    fx["pd_nullable_Int64_NA"] = ni
    # 5. big int64 (> 2**53) column
    bi = base.copy()
    bi["big"] = np.int64(2**53 + 1)
    fx["pd_int64_gt_2p53"] = bi
    # 6. float32 only
    fx["pd_float32_only"] = base.astype("float32")
    # 7. bool column
    bo = base.copy()
    bo["flag"] = np.arange(len(bo)) % 2 == 0
    fx["pd_bool_col"] = bo
    # 8. time-major (interleaved) long sort, as from a SQL ORDER BY time
    fx["pd_time_major_sorted"] = base.sort_index(level="time")
    # 9. unused levels after selection
    fx["pd_unused_levels"] = base.loc[["s0", "s2"]]
    # 10. business-day freq single series
    s = pd.Series(np.arange(15.0), index=pd.bdate_range("2000-01-03", periods=15),
                  name="y")
    fx["pd_series_B"] = s
    # 11. timedelta index
    fx["pd_series_timedelta"] = pd.Series(np.arange(5.0), index=pd.timedelta_range(
        "0s", periods=5, freq="s"))
    # 12. float time index
    fx["pd_series_float_index"] = pd.Series(np.arange(5.0), index=[0.0, 0.5, 1, 1.5, 2])
    # 13. MultiIndex columns
    mc = base.copy()
    mc.columns = pd.MultiIndex.from_tuples([("a", "x"), ("a", "y")])
    fx["pd_multiindex_columns"] = mc
    # 14. datetime64[s] unit (pandas 2 non-ns)
    su = base.reset_index()
    su["time"] = su["time"].astype("datetime64[s]")
    fx["pd_time_unit_s"] = su.set_index(["h0", "time"])
    # 15. empty panel
    fx["pd_empty"] = base.iloc[:0]
    # 16. single-row instances
    fx["pd_single_row_instances"] = base.groupby(level=0).head(1)
    # 17. mixed per-instance frequencies
    a = pd.DataFrame({"c0": np.arange(10.0)}, index=pd.MultiIndex.from_product(
        [["a"], pd.date_range("2000", periods=10, freq="D")], names=["h0", "time"]))
    b = pd.DataFrame({"c0": np.arange(10.0)}, index=pd.MultiIndex.from_product(
        [["b"], pd.date_range("2000", periods=10, freq="h")], names=["h0", "time"]))
    fx["pd_mixed_freq_instances"] = pd.concat([a, b])
    # 18. column name collides with a key name / integer column names
    ic = base.copy()
    ic.columns = [0, 1]
    fx["pd_int_column_names"] = ic
    # 19. duplicate timestamps in an instance
    fx["pd_duplicate_timestamps"] = pd.concat([base.iloc[:3], base.iloc[:3]]).sort_index(
        kind="stable")
    # 20. pandas 3 / pyarrow-backed string keys
    try:
        k = base.reset_index()
        k["h0"] = k["h0"].astype("string[pyarrow]")
        fx["pd_arrow_string_keys"] = k.set_index(["h0", "time"])
    except Exception:  # noqa: BLE001
        pass

    # polars
    pll = pl.from_pandas(base.reset_index())
    kw = {"key_cols": ["h0"], "time_col": "time"}
    mixed = pll.with_columns(pl.when(pl.int_range(pl.len()) == 3).then(float("nan"))
                             .when(pl.int_range(pl.len()) == 5).then(None)
                             .otherwise(pl.col("c0")).alias("c0"))
    fx["pl_nan_and_null_same_col"] = (mixed, kw)
    fx["pl_tz_aware"] = (pll.with_columns(pl.col("time").dt.replace_time_zone(
        "Europe/Berlin")), kw)
    fx["pl_null_key"] = (pll.with_columns(pl.when(pl.col("h0") == "s1").then(None)
                                          .otherwise(pl.col("h0")).alias("h0")), kw)
    fx["pl_int64_big"] = (pll.with_columns(pl.lit(2**53 + 1, dtype=pl.Int64)
                                           .alias("big")), kw)
    fx["pl_float32"] = (pll.with_columns(pl.col("c0", "c1").cast(pl.Float32)), kw)
    fx["pl_time_major"] = (pll.sort("time", maintain_order=True), kw)
    fx["pl_two_keys"] = (pll.with_columns(pl.lit("g").alias("g")).select(
        "g", "h0", "time", "c0", "c1"), {"key_cols": ["g", "h0"], "time_col": "time"})
    fx["pl_int_time"] = (pll.with_columns(pl.int_range(pl.len()).over("h0")
                                          .alias("time")), kw)
    fx["pl_enum_key"] = (pll.with_columns(pl.col("h0").cast(pl.Enum(
        ["s0", "s1", "s2", "s3"]))), kw)
    # arrow
    pat = pa.Table.from_pandas(base.reset_index(), preserve_index=False
                               ).replace_schema_metadata(None)
    c0 = pat.column("c0").to_pylist()
    c0[3] = float("nan")
    c0[5] = None
    fx["pa_nan_and_null_same_col"] = (pat.set_column(2, "c0", pa.array(c0)), kw)
    fx["pa_large_string_key"] = (pat.set_column(0, "h0", pat.column("h0").cast(
        pa.large_string())), kw)
    fx["pa_timestamp_ms_tz"] = (pat.set_column(1, "time", pat.column("time").cast(
        pa.timestamp("ms", tz="UTC"))), kw)
    fx["pa_time_major"] = (pat.sort_by("time"), kw)
    return fx


def main():
    import polars as pl
    import pyarrow as pa

    rows = []
    for name, v in fixtures().items():
        native, kw = v if isinstance(v, tuple) else (v, {})
        rec = {"fixture": name}
        try:
            hub = H.from_native(native, **kw)
            out = H.to_native(hub)
            if isinstance(native, (pd.DataFrame, pd.Series)):
                ok, why = pd_equal(out, native)
            elif isinstance(native, (pl.DataFrame, pl.LazyFrame)):
                ok, why = pl_equal(out, native)
            else:
                ok, why = pa_equal(out, native)
            rec.update(ok=bool(ok), reason="" if ok else why)
        except Exception as e:  # noqa: BLE001
            rec.update(ok=False, reason=f"ERROR {type(e).__name__}: "
                       f"{str(e).splitlines()[0][:140] if str(e) else ''}",
                       tb=traceback.format_exc().splitlines()[-2:])
        rows.append(rec)
        print(f"{name:28s} ok={rec['ok']!s:5s} {rec['reason'][:150]}")

    # per-slice trusted freq on mixed-frequency panel
    X = fixtures()["pd_mixed_freq_instances"]
    hub = H.from_native(X)
    sv = hub.slice(1)
    v = sv.to_pandas(freq_mode="trusted")
    true_b = X.xs("b").index
    trusted = {
        "hub_global_freq": hub.tmeta.freq,
        "slice_b_trusted_freq": str(v.index.freq),
        "slice_b_inferred_freq": pd.infer_freq(true_b),
        "slice_b_index_values_equal": bool(v.index.equals(true_b)),
    }
    try:
        pd.DatetimeIndex(v.index, freq="infer")
        trusted["freq_conforms"] = None
    except Exception:  # noqa: BLE001
        pass
    try:
        pd.DatetimeIndex(np.asarray(v.index), freq=v.index.freq)
        trusted["validated_ctor_accepts"] = True
    except ValueError as e:
        trusted["validated_ctor_accepts"] = f"ValueError: {str(e)[:100]}"
    # HubNaive future time for instance b vs sktime NaiveForecaster
    from sktime.forecasting.naive import NaiveForecaster

    fh = np.arange(1, 4)
    hub_pred = H.to_native(H.hub_vectorize(hub, lambda: H.HubNaive("last"), fh))
    try:
        sk_pred = NaiveForecaster(strategy="last").fit(X, fh=fh).predict()
        trusted["sktime_panel_fit"] = "ok"
    except ValueError as e:
        trusted["sktime_panel_fit"] = f"ValueError: {str(e)[:120]}"
        sk_pred = pd.concat({k: NaiveForecaster(strategy="last").fit(
            X.xs(k), fh=fh).predict() for k in ["a", "b"]}, names=["h0"])
    trusted["hub_pred_b_times"] = [str(t) for t in hub_pred.xs("b").index]
    trusted["sktime_pred_b_times"] = [str(t) for t in sk_pred.xs("b").index]
    trusted["hub_matches_sktime"] = trusted["hub_pred_b_times"] == trusted[
        "sktime_pred_b_times"]
    print(json.dumps(trusted, indent=1))
    tag = "pd" + pd.__version__.split(".")[0]
    with open(os.path.join(ED, "results", f"x6_proto_hub_verify0_fidelity_{tag}.json"),
              "w") as f:
        json.dump({"env": env_info(), "rows": rows, "mixed_freq": trusted}, f, indent=1,
                  default=str)
    print("pass", sum(r["ok"] for r in rows), "/", len(rows))


if __name__ == "__main__":
    main()
